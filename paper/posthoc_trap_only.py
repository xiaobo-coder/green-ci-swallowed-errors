"""922 POST HOC (not preregistered), 2026-11-18, after top-venue mock review: trap-only H1/H2 (P-N, S-N) exact sign-flip over
confirmatory families + family bootstrap CI, and Holm over all 12 preregistered tests (H1-H3 x 4 models). Reads frozen results only.
Run from the 922 folder: /usr/bin/python3 -I paper/posthoc_trap_only.py OUT.tex"""
import collections, itertools, json, os, random, sys
HERE = os.path.dirname(os.path.abspath(__file__)); R = os.path.join(HERE, '..', 'study-v0.5', 'results')
obs = json.load(open(os.path.join(R, 'observer-test-001', 'observer.json')))
SHORT = {'qwen/qwen3.6-35b-a3b': 'Qa', 'openai/gpt-oss-20b': 'Go', 'ollama:qwen3.6:27b-coding-mtp-q4_K_M': 'Qc', 'codex:openai.gpt-5.6-luna:high': 'Cx'}
def sign_flip(d):
    T = sum(d); n = len(d); ge = sum(1 for sg in itertools.product((1, -1), repeat=n) if abs(sum(a * b for a, b in zip(sg, d))) >= abs(T) - 1e-12)
    return T / n, ge / 2 ** n
def boot(d, B=10000, seed=922):
    r = random.Random(seed); n = len(d); ms = sorted(sum(r.choice(d) for _ in range(n)) / n for _ in range(B)); return ms[int(.025 * B)], ms[int(.975 * B) - 1]
def holm(ps):
    o = sorted(range(len(ps)), key=lambda i: ps[i]); out = [0] * len(ps); run = 0
    for k, i in enumerate(o): run = max(run, min(1, (len(ps) - k) * ps[i])); out[i] = run
    return out
sgn = lambda v: ('%+.1f' % (100 * v)).replace('-', '$-$'); pv = lambda p: '<0.001' if p < 0.001 else '%.3f' % p
mac = []; allp = []; keys = []
for run in obs['runs']:
    s = SHORT[run['model']]
    per = collections.defaultdict(lambda: collections.defaultdict(lambda: [0, 0]))
    for e in run['episodeDetail']:
        if e['holdout'] or e['systemFailure'] or e['cond'] not in 'NPS': continue
        for w in e['cls']['warnings']:
            if w['kind'] == 'TP' and w['trap']: x = per[e['cond']][e['family']]; x[0] += w['snf']; x[1] += 1
    for nm, (cx, cy) in {'HOne': ('P', 'N'), 'HTwo': ('S', 'N')}.items():
        fams = sorted(set(per[cx]) & set(per[cy])); d = [per[cx][f][0] / per[cx][f][1] - per[cy][f][0] / per[cy][f][1] for f in fams]
        mean, p = sign_flip(d); lo, hi = boot(d)
        mac += ['\\newcommand{\\PH%s%sTrap}{%s}' % (s, nm, sgn(mean)), '\\newcommand{\\PH%s%sTrapP}{%s}' % (s, nm, pv(p)), '\\newcommand{\\PH%s%sTrapCI}{[%s, %s]}' % (s, nm, sgn(lo), sgn(hi)), '\\newcommand{\\PH%s%sTrapNfam}{%d}' % (s, nm, len(fams))]
        print(s, nm, 'trap-only', round(100 * mean, 1), 'p', round(p, 4), 'CI', round(100 * lo, 1), round(100 * hi, 1), 'fams', len(fams))
    for k, v in run['analysis']['tests'].items(): allp.append(v['pTwoSided']); keys.append((s, k))
for (s, k), ph in zip(keys, holm(allp)):
    nm = {'H1_snf_P_minus_N': 'HOne', 'H2_snf_S_minus_N': 'HTwo', 'H3_suppression_FP_minus_TP_in_N': 'HThree'}[k]
    mac.append('\\newcommand{\\PH%s%sHolmAll}{%s}' % (s, nm, pv(ph))); print(s, k, 'Holm over 12:', round(ph, 4))
open(sys.argv[1], 'x').write('% POST HOC (not preregistered): generated by paper/posthoc_trap_only.py from frozen results\n' + '\n'.join(mac) + '\n')
