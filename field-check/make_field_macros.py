#!/usr/bin/env python3
"""Render \F* macros from field-check summary.json (post hoc). Usage: python3 -I make_field_macros.py summary.json out.tex"""
import json, sys
s = json.load(open(sys.argv[1]))['byAgent']; out = []
def m(k, v): out.append('\\newcommand{\\F%s}{%s}' % (k, v))
names = {'Claude Code': 'Claude', 'Cursor Agent': 'Cursor', 'Codex': 'Codex'}
tot = {k: sum(a[k] for a in s.values()) for k in next(iter(s.values()))}
for nm, a in list(s.items()) + [('Total', tot)]:
    n = names.get(nm, nm); pct = lambda x, y: '%.0f' % (100 * x / y) if y else '--'
    m(n + 'Events', '{:,}'.format(a['events'])); m(n + 'EventsPy', '{:,}'.format(a['eventsPy'])); m(n + 'Handlers', '{:,}'.format(a['handlersAdded']))
    m(n + 'BroadPct', pct(a['broadAdded'], a['handlersAdded'])); m(n + 'BroadSwallowPct', pct(a['broadSwallowAdded'], a['handlersAdded']))
    m(n + 'EvBroadSwallowPct', pct(a['eventsBroadSwallow'], a['eventsPy'])); m(n + 'EvNarrowPct', pct(a['eventsNarrowing'], a['eventsPy']))
    m(n + 'EvNarrow', '{:,}'.format(a['eventsNarrowing'])); m(n + 'EvBroadSwallow', '{:,}'.format(a['eventsBroadSwallow']))
    m(n + 'BroadSwallowOfBroadPct', pct(a['broadSwallowAdded'], a['broadAdded'])); m(n + 'Specific', '{:,}'.format(a['specificAdded'])); m(n + 'SpecSwallowOfSpecPct', pct(a['specificSwallowAdded'], a['specificAdded']))
    m(n + 'SuppAdded', '{:,}'.format(a['suppAdded'])); m(n + 'SuppRemoved', '{:,}'.format(a['suppRemoved'])); m(n + 'EvSuppPct', pct(a['eventsSuppAdded'], a['eventsPy']))
m('ClaudeSharePct', '%.0f' % (100 * s['Claude Code']['events'] / tot['events']))
open(sys.argv[2], 'x').write('%% generated by make_field_macros.py from AgentPack field check (post hoc)\n' + '\n'.join(out).replace('{,}', '{,}') + '\n')
